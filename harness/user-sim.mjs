#!/usr/bin/env node
// Simulate what an ordinary user would type to a coding agent for a product idea.
// The simulator sees only the persona and the idea — never a blueprint — so the
// brief carries no knowledge the blueprint is supposed to add.
//
//   node harness/user-sim.mjs --out <file> [--persona <text>] [--idea <text>]
//
// Generate once, read it, then freeze it: every A and B run of an experiment
// must start from the same brief.

import fs from "node:fs";
import os from "node:os";
import path from "node:path";
import { runAgent, sessionId } from "./lib/opencode.mjs";
import { HARNESS, MODELS, fill } from "./lib/run.mjs";

const DEFAULTS = {
  persona:
    "一位独立开发者，有几年 Web 开发经验，但没有做过完整的商业 SaaS。打算一个人加上 AI 编程助手把产品做出来，卖给小团队。",
  idea: "一个给小团队用的 AI 研究/文档助手：大家把资料放进去，提出问题，它帮忙研读资料、写出带出处的研究报告。",
};

const opts = { ...DEFAULTS };
const argv = process.argv.slice(2);
for (let i = 0; i < argv.length; i++) {
  if (argv[i] === "--out") opts.out = path.resolve(argv[++i]);
  else if (argv[i] === "--persona") opts.persona = argv[++i];
  else if (argv[i] === "--idea") opts.idea = argv[++i];
  else {
    console.error(`unknown argument ${argv[i]}`);
    process.exit(1);
  }
}
if (!opts.out) {
  console.error("usage: user-sim.mjs --out <file> [--persona <text>] [--idea <text>]");
  process.exit(1);
}
if (fs.existsSync(opts.out)) {
  console.error(`${opts.out} exists: a frozen brief is never regenerated`);
  process.exit(1);
}

// An empty working directory with an agent that may not touch anything.
const dir = fs.mkdtempSync(path.join(os.tmpdir(), "user-sim-"));
fs.mkdirSync(path.join(dir, ".opencode", "agents"), { recursive: true });
fs.copyFileSync(path.join(HARNESS, "agents", "user-sim.md"), path.join(dir, ".opencode", "agents", "user-sim.md"));

const message = fill(fs.readFileSync(path.join(HARNESS, "prompts", "user-sim.md"), "utf8"), opts);
const result = await runAgent({
  cwd: dir,
  agent: "user-sim",
  model: MODELS.userSim,
  session: sessionId("usersim", Date.now().toString()),
  message,
  logFile: path.join(dir, "log.jsonl"),
  timeoutMs: 10 * 60 * 1000,
});
const brief = (result.finalText || result.allText).trim();
if (result.exitCode !== 0 || !brief) {
  console.error(`user-sim failed (exit ${result.exitCode}): ${result.errors.join("; ")} — log ${dir}/log.jsonl`);
  process.exit(1);
}
fs.mkdirSync(path.dirname(opts.out), { recursive: true });
fs.writeFileSync(
  opts.out,
  [
    "<!-- Generated by harness/user-sim.mjs (" + MODELS.userSim + ") on " + new Date().toISOString().slice(0, 10) + ".",
    "     Persona: " + opts.persona,
    "     Idea: " + opts.idea,
    "     Frozen: every run of this experiment uses this exact text. -->",
    "",
    brief,
    "",
  ].join("\n"),
);
console.log(brief);
console.log(`\nuser-sim: written to ${opts.out}`);
