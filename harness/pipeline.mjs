#!/usr/bin/env node
// Template production pipeline (v1: adapt an existing blueprint to a new product of the same category).
//
//   node harness/pipeline.mjs new --id <name> --adapt-from <blueprint> (--brief <file> | --idea <text> [--persona <text>])
//        [--adapt-model <m>] [--review-model <m>] [--author-contract <m>] [--author-spec <m>]
//        [--author-journeys <m>] [--ref-model <m>]
//   node harness/pipeline.mjs run    --id <name> [--until <step>]     run pending steps in order
//   node harness/pipeline.mjs status --id <name>
//
// Steps (each is recorded in <runs>/pipeline-<id>/state.json and is resumable; a step that fails stops the run):
//   brief     freeze the user brief (given, or generated by user-sim)
//   adapt     an agent adapts the source blueprint to the brief  -> blueprints/<id>
//   review    an independent read-only agent reviews the draft    -> REVIEW.md
//   fix       the adapter fixes the review findings               -> blueprints/<id>
//   authors   four held-out authors (contract, spec, journeys, journeys-api) in parallel
//   reference a reference implementation (B + tests, not scored)
//   admit     run every authored suite on the reference; failing tests go to a blind adjudicator
//   freeze    copy the admitted suites into experiments/<id>/pack and tag
// Validation builds (control / tests-only / full) are launched separately with baseline.mjs / build.mjs
// once the pack is frozen; the pipeline records its own wall time and agent turns as the adaptation cost.
//
// Every shell-out passes arguments as an array: never build a command line as one string (zsh does not split it).

import fs from "node:fs";
import path from "node:path";
import { spawn, execFileSync } from "node:child_process";
import { HARNESS, REPO, RUNS, MODELS, runPaths, blueprintDir } from "./lib/run.mjs";
import { runAgent, sessionId, FALLBACK_MODEL } from "./lib/opencode.mjs";
import { assertSandboxAvailable, writeProfile } from "./lib/sandbox.mjs";

const STEPS = ["brief", "adapt", "review", "fix", "authors", "reference", "admit", "freeze"];

function parse(argv) {
  const [command, ...rest] = argv;
  const o = { command };
  for (let i = 0; i < rest.length; i += 2) o[rest[i].replace(/^--/, "")] = rest[i + 1];
  return o;
}
const o = parse(process.argv.slice(2));
if (!o.command || !o.id) usage();
function usage() {
  console.error("usage: pipeline.mjs new|run|status --id <name> …");
  process.exit(2);
}

const root = path.join(RUNS, `pipeline-${o.id}`);
const stateFile = path.join(root, "state.json");
const load = () => JSON.parse(fs.readFileSync(stateFile, "utf8"));
const save = (s) => fs.writeFileSync(stateFile, JSON.stringify(s, null, 2));
const log = (s, msg) => {
  fs.appendFileSync(path.join(root, "log.jsonl"), JSON.stringify({ t: new Date().toISOString(), msg }) + "\n");
  console.log(`pipeline[${s.id}]: ${msg}`);
};
const node = (args, opts = {}) => execFileSync("node", args, { encoding: "utf8", stdio: ["ignore", "pipe", "pipe"], ...opts });
const bg = (args, logFile) =>
  new Promise((resolve) => {
    const out = fs.openSync(logFile, "a");
    const p = spawn("node", args, { stdio: ["ignore", out, out] });
    p.on("close", (code) => resolve(code));
  });

// ---- an isolated agent job: the agent sees only its own project dir ----
const AGENT_MD = (allow) => `---
description: Pipeline agent. Edits only the allowed paths.
mode: primary
steps: 1200
permissions:
  - action: edit
    resource: "*"
    effect: deny
${allow.map((g) => `  - action: edit\n    resource: "${g}"\n    effect: allow`).join("\n")}
  - action: webfetch
    resource: "*"
    effect: deny
  - action: websearch
    resource: "*"
    effect: deny
  - action: external_directory
    resource: "*"
    effect: deny
  - action: shell
    resource: "*"
    effect: allow
  - action: shell
    resource: "git push*"
    effect: deny
  - action: shell
    resource: "sudo *"
    effect: deny
---

You work only inside this project directory. Never read, print or copy secrets.
`;

async function agentJob(s, name, { model, allow, message, populate }) {
  const runId = `pipeline-${s.id}-${name}`;
  const p = runPaths(runId);
  fs.rmSync(p.root, { recursive: true, force: true });
  fs.mkdirSync(p.records, { recursive: true });
  fs.mkdirSync(path.join(p.project, ".opencode", "agents"), { recursive: true });
  populate(p.project);
  fs.copyFileSync(path.join(HARNESS, "agents", "opencode.jsonc"), path.join(p.project, "opencode.jsonc"));
  fs.writeFileSync(path.join(p.project, ".opencode", "agents", "job.md"), AGENT_MD(allow));
  execFileSync("git", ["init", "-q", "-b", "main"], { cwd: p.project });
  assertSandboxAvailable();
  const sandbox = writeProfile(p.sandbox, p.project);
  fs.mkdirSync(path.join(p.records, "logs"), { recursive: true });
  const session = sessionId(runId, name, Date.now());
  let result;
  for (let round = 1; round <= 4; round++) {
    result = await runAgent({
      cwd: p.project,
      agent: "job",
      model,
      session,
      message: round === 1 ? message : "Continue until the work is complete. End with the single word DONE.",
      logFile: path.join(p.records, "logs", `${name}-r${round}.jsonl`),
      sandbox,
    });
    s.turns.push({ step: name, round, model: result.modelUsed ?? model, fellBack: !!result.fellBack, ms: result.ms, exit: result.exitCode });
    save(s);
    if (/(^|\n)\s*DONE\s*$/.test((result.finalText || result.allText).trim())) break;
  }
  return p;
}

// ---- steps ----
const STEP = {
  async brief(s) {
    const dest = path.join(REPO, "experiments", s.id, "user-brief.md");
    fs.mkdirSync(path.dirname(dest), { recursive: true });
    if (s.briefFile) fs.copyFileSync(s.briefFile, dest);
    else if (!fs.existsSync(dest)) {
      const a = [path.join(HARNESS, "user-sim.mjs"), "--out", dest, "--idea", s.idea];
      if (s.persona) a.push("--persona", s.persona);
      node(a);
    }
    s.brief = dest;
  },

  async adapt(s) {
    const src = blueprintDir(s.adaptFrom);
    const dest = path.join(REPO, "blueprints", s.id);
    if (fs.existsSync(dest)) throw new Error(`blueprints/${s.id} already exists`);
    const message = `Adapt the blueprint in ./source (product: see ./brief/user-brief.md) into a new blueprint for the NEW product in ./blueprint, same structure and style, same language as the source. Read ./source/TEMPLATE.md, spec/, stages/ and acceptance/ (lib and tests) first. Reuse as much as is sensible, byte for byte where nothing changes: that reuse is part of what we measure. Rewrite product.md, api.yaml, architecture.md (keep sections 5-9, the testability contract: fake model, test routes, start convention, UI anchors, what the suite may inspect in the database), decisions.md (human decision points with recommended defaults, marked 'unanswered, evaluation uses the default'), review-checklist.md, the stage documents and the acceptance tests (about 60-75 black-box tests; vitest/chai only, no Playwright matchers; setup calls send JSON; helper functions that assert their own status must not be wrapped in expectStatus). Every rule a test depends on must be stated in api.yaml or architecture.md sections 5-9, because a control builder sees only those. Also write ./blueprint/ADAPTATION-LOG.md (what was reused, rewritten, decisions needing a human). Finish with a short summary and the single word DONE.`;
    const p = await agentJob(s, "adapt", {
      model: s.models.adapt,
      allow: ["blueprint/**"],
      message,
      populate: (proj) => {
        fs.cpSync(src, path.join(proj, "source"), { recursive: true, verbatimSymlinks: true, filter: (f) => !/acceptance-results|\.DS_Store/.test(f) });
        fs.mkdirSync(path.join(proj, "brief"), { recursive: true });
        fs.copyFileSync(s.brief, path.join(proj, "brief", "user-brief.md"));
        fs.cpSync(src, path.join(proj, "blueprint"), { recursive: true, verbatimSymlinks: true, filter: (f) => !/acceptance-results|\.DS_Store/.test(f) });
      },
    });
    fs.cpSync(path.join(p.project, "blueprint"), dest, { recursive: true, verbatimSymlinks: true, filter: (f) => !/acceptance-results|\.DS_Store/.test(f) });
    s.blueprint = dest;
  },

  async review(s) {
    const dest = path.join(REPO, "experiments", s.id, "REVIEW.md");
    const p = await agentJob(s, "review", {
      model: s.models.review,
      allow: ["REVIEW.md"],
      message: `Independent read-only review of the draft blueprint in ./blueprint (compare with ./source, the blueprint it was adapted from, and ./brief/user-brief.md). Write REVIEW.md in Chinese, prioritized (blocking / should fix / nice), each finding with file:line, why, and a concrete fix. Check: tests assert only what api.yaml / architecture.md sections 5-9 state (a control builder sees only those); test bugs (Playwright-only matchers in vitest, helpers that assert their own status wrapped in expectStatus, non-JSON setup, shared mutable mocks, fixed sleeps, order dependence); contradictions between spec files and tests; unobservable requirements; arithmetic of any budget/money numbers (recompute); coverage of the brief. Finish with DONE.`,
      populate: (proj) => {
        fs.cpSync(blueprintDir(s.id), path.join(proj, "blueprint"), { recursive: true, verbatimSymlinks: true, filter: (f) => !/acceptance-results|\.DS_Store/.test(f) });
        fs.cpSync(blueprintDir(s.adaptFrom), path.join(proj, "source"), { recursive: true, verbatimSymlinks: true, filter: (f) => !/acceptance-results|\.DS_Store|node_modules/.test(f) });
        fs.mkdirSync(path.join(proj, "brief"), { recursive: true });
        fs.copyFileSync(s.brief, path.join(proj, "brief", "user-brief.md"));
      },
    });
    fs.copyFileSync(path.join(p.project, "REVIEW.md"), dest);
    s.reviewFile = dest;
  },

  async fix(s) {
    const dest = blueprintDir(s.id);
    const p = await agentJob(s, "fix", {
      model: s.models.adapt,
      allow: ["blueprint/**"],
      message: "Fix every blocking and should-fix finding in ./REVIEW.md in the blueprint in ./blueprint. Keep the control-builder principle: any rule a test depends on is stated in api.yaml or architecture.md sections 5-9. Append what you changed to blueprint/ADAPTATION-LOG.md. Finish with DONE.",
      populate: (proj) => {
        fs.cpSync(dest, path.join(proj, "blueprint"), { recursive: true, verbatimSymlinks: true, filter: (f) => !/acceptance-results|\.DS_Store/.test(f) });
        fs.copyFileSync(s.reviewFile, path.join(proj, "REVIEW.md"));
      },
    });
    fs.rmSync(dest, { recursive: true, force: true });
    fs.cpSync(path.join(p.project, "blueprint"), dest, { recursive: true, verbatimSymlinks: true, filter: (f) => !/acceptance-results|\.DS_Store/.test(f) });
    execFileSync("git", ["add", "-A"], { cwd: REPO });
    execFileSync("git", ["commit", "-qm", `blueprints: ${s.id} draft (pipeline)\n\nCo-Authored-By: Claude Sonnet 5.5 <noreply@anthropic.com>`], { cwd: REPO });
    execFileSync("git", ["tag", "-f", `blueprint-${s.id}-draft`], { cwd: REPO });
  },

  async authors(s) {
    const L = path.join(RUNS, "_logs");
    fs.mkdirSync(L, { recursive: true });
    const jobs = [
      ["contract", s.models.authorContract],
      ["spec", s.models.authorSpec],
      ["journeys", s.models.authorJourneys],
      ["journeys-api", s.models.authorJourneys],
    ];
    s.authorRuns = {};
    await Promise.all(
      jobs.map(async ([bucket, model]) => {
        const id = `${s.id}-H-${bucket}`;
        s.authorRuns[bucket] = id;
        node([path.join(HARNESS, "holdout.mjs"), "new", "--bucket", bucket, "--model", model, "--run", id, "--blueprint", s.id, "--brief", s.brief]);
        const code = await bg([path.join(HARNESS, "holdout.mjs"), "go", "--run", id], path.join(L, `${id}.log`));
        if (code !== 0) throw new Error(`author ${id} exited ${code}`);
      }),
    );
  },

  async reference(s) {
    const id = `${s.id}-REF`;
    node([path.join(HARNESS, "baseline.mjs"), "new", "--blueprint", s.id, "--brief", s.brief, "--run", id, "--builder-model", s.models.ref, "--with-tests"]);
    const code = await bg([path.join(HARNESS, "baseline.mjs"), "go", "--run", id], path.join(RUNS, "_logs", `${id}.log`));
    if (code !== 0) throw new Error(`reference build exited ${code}`);
    s.referenceRun = id;
  },

  async admit(s) {
    // Run all suites on the reference. Failing tests are written to a digest; the adjudicator step is a human/agent
    // action recorded in experiments/<id>/pack/adjudication.json (see PROTOCOL.md section 4).
    const out = path.join(root, "admit");
    fs.rmSync(out, { recursive: true, force: true });
    const suites = Object.values(s.authorRuns).map((r) => path.join(runPaths(r).project, "blueprint", "acceptance"));
    node([path.join(HARNESS, "eval.mjs"), "score", "--suites", suites.join(","), "--runs", s.referenceRun, "--out", out, "--jobs", "1"]);
    const sc = JSON.parse(fs.readFileSync(path.join(out, "scores.json"), "utf8"));
    const failing = Object.entries(sc.res).filter(([, v]) => v[s.referenceRun] !== "passed").map(([k]) => k);
    fs.writeFileSync(path.join(root, "admit-failing.json"), JSON.stringify(failing, null, 2));
    s.admitFailing = failing.length;
    if (failing.length) {
      s.needsAdjudication = true;
      throw new Error(`${failing.length} authored tests fail on the reference; adjudicate them (digest: ${path.join(root, "admit-failing.json")}), fix or exclude, then re-run: node harness/pipeline.mjs run --id ${s.id}`);
    }
  },

  async freeze(s) {
    const pack = path.join(REPO, "experiments", s.id, "pack");
    for (const [bucket, id] of Object.entries(s.authorRuns)) {
      const src = path.join(runPaths(id).project, "blueprint", "acceptance", "tests", "s4");
      fs.mkdirSync(path.join(pack, "suites", id), { recursive: true });
      fs.cpSync(src, path.join(pack, "suites", id, "s4"), { recursive: true });
    }
    execFileSync("git", ["add", "-A"], { cwd: REPO });
    execFileSync("git", ["commit", "-qm", `${s.id}: frozen eval pack (pipeline)\n\nCo-Authored-By: Claude Sonnet 5.5 <noreply@anthropic.com>`], { cwd: REPO });
    execFileSync("git", ["tag", "-f", `${s.id}-pack-v1`], { cwd: REPO });
  },
};

// ---- commands ----
if (o.command === "new") {
  if (!o["adapt-from"] || (!o.brief && !o.idea)) usage();
  if (fs.existsSync(stateFile)) throw new Error(`pipeline ${o.id} exists`);
  blueprintDir(o["adapt-from"]);
  fs.mkdirSync(root, { recursive: true });
  const m = (k, d) => o[k] ?? d;
  save({
    id: o.id,
    adaptFrom: o["adapt-from"],
    briefFile: o.brief ? path.resolve(o.brief) : null,
    idea: o.idea ?? null,
    persona: o.persona ?? null,
    models: {
      adapt: m("adapt-model", MODELS.builder),
      review: m("review-model", MODELS.reviewer),
      authorContract: m("author-contract", "opencode-go/minimax-m3.1-flash-free"),
      authorSpec: m("author-spec", "opencode-go/beam-free"),
      authorJourneys: m("author-journeys", "opencode-go/minimax-m3.1-flash-free"),
      ref: m("ref-model", MODELS.builder),
      fallback: FALLBACK_MODEL,
    },
    done: {},
    turns: [],
    startedAt: Date.now(),
  });
  console.log(`pipeline ${o.id} created at ${root}\nnext: node harness/pipeline.mjs run --id ${o.id}`);
} else if (o.command === "status") {
  const s = load();
  for (const st of STEPS) console.log(`${s.done[st] ? "done   " : "pending"} ${st}${s.done[st] ? `  (${Math.round((s.done[st].ms ?? 0) / 60000)} min)` : ""}`);
  const fb = s.turns.filter((t) => t.fellBack).length;
  console.log(`agent turns: ${s.turns.length}${fb ? `, ${fb} used the fallback model` : ""}`);
} else if (o.command === "run") {
  const s = load();
  const until = o.until ?? STEPS[STEPS.length - 1];
  for (const st of STEPS) {
    if (s.done[st]) continue;
    const t0 = Date.now();
    log(s, `step ${st} …`);
    try {
      await STEP[st](s);
    } catch (e) {
      save(s);
      log(s, `step ${st} stopped: ${e.message}`);
      process.exit(1);
    }
    s.done[st] = { ms: Date.now() - t0, at: new Date().toISOString() };
    save(s);
    log(s, `step ${st} done in ${Math.round((Date.now() - t0) / 60000)} min`);
    if (st === until) break;
  }
} else usage();
